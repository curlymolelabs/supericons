-- Final search outcome telemetry.
--
-- Rollback plan, written before implementation:
-- 1. Set search_telemetry_settings.dashboard_source to legacy.
-- 2. Set search_telemetry_settings.web_ingestion_enabled to false.
-- 3. Drop the MCP copy trigger so new MCP events stop entering the final ledger.
-- 4. Keep every final outcome, diagnostic, cutover timestamp, and linkage column.
-- 5. Restore the Local MCP suppression only through its separate rollback file.
-- 6. Website and MCP search continue because every telemetry write is best effort.
--
-- Backward compatibility:
-- - Existing search_request_audit and mcp_usage_events writers keep working.
-- - No existing column is renamed, removed, or made more restrictive.
-- - Existing rows are not assigned manufactured episode or attempt identities.
-- - The dashboard remains on its legacy source until a later guarded cutover.

