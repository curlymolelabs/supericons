create or replace function public.si_take_web_search_telemetry_rate_limit(
  p_subject_hash text,
  p_limit integer default 120,
  p_window_seconds integer default 60
)
returns table (
  allowed boolean,
  remaining integer,
  retry_after_seconds integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_subject_hash text := lower(trim(coalesce(p_subject_hash, '')));
  v_limit integer := p_limit;
  v_window_seconds integer := p_window_seconds;
  v_window_start timestamptz;
  v_count integer;
begin
  if v_subject_hash !~ '^[a-f0-9]{64}$' then
    raise exception 'subject_hash must be a sha256 value' using errcode = '22023';
  end if;
  if v_limit < 1 or v_limit > 10000 then
    raise exception 'limit is outside the supported range' using errcode = '22023';
  end if;
  if v_window_seconds < 10 or v_window_seconds > 3600 then
    raise exception 'window_seconds is outside the supported range' using errcode = '22023';
  end if;

  v_window_start := to_timestamp(
    floor(extract(epoch from timezone('utc', now())) / v_window_seconds) * v_window_seconds
  );

  insert into public.search_telemetry_rate_limits (
    subject_hash,
    window_started_at,
    request_count,
    updated_at
  ) values (
    v_subject_hash,
    v_window_start,
    1,
    timezone('utc', now())
  )
  on conflict (subject_hash, window_started_at)
  do update set
    request_count = public.search_telemetry_rate_limits.request_count + 1,
    updated_at = timezone('utc', now())
  returning request_count into v_count;

  if mod(abs(hashtext(v_subject_hash)), 100) = 0 then
    delete from public.search_telemetry_rate_limits
    where updated_at < timezone('utc', now()) - interval '1 day';
  end if;

  return query select
    v_count <= v_limit,
    greatest(v_limit - v_count, 0),
    greatest(
      1,
      ceil(extract(epoch from (v_window_start + make_interval(secs => v_window_seconds) - timezone('utc', now()))))::integer
    );
end;
$$;

