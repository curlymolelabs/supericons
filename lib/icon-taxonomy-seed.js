function normalizeIconText(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/[_:]+/g, ' ')
    .replace(/[^a-z0-9\s-]/g, ' ')
    .replace(/-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function iconText(icon = {}) {
  return normalizeIconText([
    icon.lib,
    icon.id,
    icon.name,
    icon.style,
    icon.type,
  ].filter(Boolean).join(' '));
}

