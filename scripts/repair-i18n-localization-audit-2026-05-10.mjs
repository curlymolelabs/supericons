import fs from 'node:fs';
import path from 'node:path';

import { SUPPORTED_LOCALES } from '../lib/i18n/locales.js';

const messagesDir = path.join('data', 'i18n', 'messages');

function read(locale) {
  return JSON.parse(fs.readFileSync(path.join(messagesDir, `${locale}.json`), 'utf8'));
}

function write(locale, catalog) {
  fs.writeFileSync(path.join(messagesDir, `${locale}.json`), `${JSON.stringify(catalog, null, 2)}\n`, 'utf8');
}

function merge(target, source) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      if (!target[key] || typeof target[key] !== 'object' || Array.isArray(target[key])) target[key] = {};
      merge(target[key], value);
    } else {
      target[key] = value;
    }
  }
}

function legalHtml(updated, sections) {
  return `<div class="terms-content"><p class="terms-content__updated">${updated}</p>${sections.map((section) => `<section class="terms-section"><h3 class="terms-section__title">${section.title}</h3>${section.body.map((line) => `<p>${line}</p>`).join('')}</section>`).join('')}</div>`;
}

function privacyPage(data) {
  return {
    pageTitle: data.title,
    bodyHtml: legalHtml(data.updated, data.headings.map((title, index) => ({ title, body: data.bodies[index] }))),
  };
}

