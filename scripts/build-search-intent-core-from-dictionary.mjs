import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function toPatternSource(value) {
  const normalized = String(value || '').trim();
  if (!normalized) return null;
  return escapeRegExp(normalized).replace(/\\[-_ ]/g, '[-_ ]').replace(/\\ /g, '[-_ ]');
}

function uniqueStrings(values = []) {
  const seen = new Set();
  const output = [];
  for (const value of values) {
    const normalized = String(value || '').trim();
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    output.push(normalized);
  }
  return output;
}

const dictionary = JSON.parse(
  readFileSync(resolve('data/search-intent-dictionary/search-intent-dictionary.json'), 'utf8'),
);
const mindMap = JSON.parse(
  readFileSync(resolve('data/search-intent-dictionary/search-intent-mind-map.json'), 'utf8'),
);
const entries = {};

for (const entry of dictionary.entries) {
  entries[entry.term] = {
    variants: entry.variants,
    prefer: entry.prefer.map((value) => toPatternSource(value)).filter(Boolean),
    avoid: entry.avoid.map((value) => toPatternSource(value)).filter(Boolean),
    avoidUnless: entry.avoid_unless || [],
  };
}

const nodesById = new Map((mindMap.nodes || []).map((node) => [node.id, node]));

for (const alias of mindMap.aliases || []) {
  const node = nodesById.get(alias.node);
  if (!node) {
    throw new Error(`Mind-map alias "${alias.term}" points to missing node "${alias.node}"`);
  }

  const variants = uniqueStrings([
    alias.term,
    ...(alias.extra_related_terms || []),
    ...(alias.extra_icon_concepts || []),
    ...(node.icon_concepts || []),
    ...(node.related_terms || []),
  ]);
  const prefer = uniqueStrings([
    ...(node.icon_concepts || []),
    ...(alias.extra_icon_concepts || []),
  ]);
  const avoid = uniqueStrings([
    ...(node.avoid_concepts || []),
    ...(alias.extra_avoid_concepts || []),
  ]);

  entries[alias.term] = {
    variants,
    prefer: prefer.map((value) => toPatternSource(value)).filter(Boolean),
    avoid: avoid.map((value) => toPatternSource(value)).filter(Boolean),
    avoidUnless: alias.avoid_unless || [],
  };
}

const output = `// Generated by scripts/build-search-intent-core-from-dictionary.mjs
// Do not edit by hand. Edit data/search-intent-dictionary/search-intent-dictionary.json instead.

export const GENERATED_INTENT_RULES = Object.freeze(${JSON.stringify(entries, null, 2)});
`;

writeFileSync(resolve('lib/generated-search-intent-rules.js'), output);
console.log('build-search-intent-core-from-dictionary: ok');
