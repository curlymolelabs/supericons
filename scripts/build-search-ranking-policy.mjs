import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const sourcePath = resolve('data/search-intent-graph/ranking-policy.json');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));

if (!Number.isInteger(source.version) || source.version < 1) {
  throw new Error('ranking-policy.json must declare a positive integer version');
}
if (!Array.isArray(source.interpretation_families) || !Array.isArray(source.query_policies)) {
  throw new Error('ranking-policy.json must contain interpretation_families and query_policies arrays');
}
if (!Array.isArray(source.brand_terms)) {
  throw new Error('ranking-policy.json must contain a brand_terms array');
}

const output = `// Generated by scripts/build-search-ranking-policy.mjs
// Do not edit by hand. Edit data/search-intent-graph/ranking-policy.json instead.

export const GENERATED_SEARCH_RANKING_POLICY = Object.freeze(${JSON.stringify(source, null, 2)});
`;

for (const target of [
  resolve('lib/generated-search-ranking-policy.js'),
  resolve('mcp/runtime/generated-search-ranking-policy.js'),
]) {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
}

console.log(`build-search-ranking-policy: ok (${source.interpretation_families.length} families, ${source.query_policies.length} query policies, ${source.brand_terms.length} brand terms)`);
