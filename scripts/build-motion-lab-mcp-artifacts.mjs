import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = dirname(__dirname);
const mcpGeneratedDir = join(repoRoot, 'mcp', 'generated');
const mcpPublicDir = join(repoRoot, 'mcp', 'public');
const hostedSharedDir = join(repoRoot, 'supabase', 'functions', '_shared', 'motion-lab');

const presetsModule = await import(pathToFileURL(join(repoRoot, 'lib', 'motion-lab-presets.js')).href);
const dataset = JSON.parse(readFileSync(join(repoRoot, 'data', 'motion-lab-preset-metadata.json'), 'utf8'));

const MOTION_LAB_SUPPORTED_TRIGGERS = ['loop', 'hover', 'click'];

const baselinePresets = presetsModule.MOTION_LAB_PRESET_IDS.map((presetId) => {
  const meta = presetsModule.MOTION_LAB_PRESET_METADATA[presetId];
  return {
    preset: presetId,
    label: meta.label,
    group: meta.group,
    description: meta.description,
    supported_triggers: [...MOTION_LAB_SUPPORTED_TRIGGERS],
  };
});

const hostedMetadataByPreset = Object.fromEntries(
  (dataset.presets || []).map((record) => [record.preset, record])
);

const hostedPresetsById = Object.fromEntries(
  presetsModule.MOTION_LAB_PRESET_IDS.map((presetId) => [presetId, presetsModule.MOTION_LAB_PRESETS[presetId]])
);

const baselinePayload = {
  version: 1,
  generated_at: new Date().toISOString(),
  presets: baselinePresets,
};

const hostedPayload = {
  version: dataset.version || 1,
  generated_at: new Date().toISOString(),
  groups: dataset.groups || [],
  supported_triggers: MOTION_LAB_SUPPORTED_TRIGGERS,
  preset_ids: presetsModule.MOTION_LAB_PRESET_IDS,
  baseline_presets: baselinePresets,
  preset_metadata_by_id: hostedMetadataByPreset,
  presets_by_id: hostedPresetsById,
};

function writeJson(filePath, value) {
  writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function writeHostedTs(filePath, payload) {
  const content = `/* eslint-disable */
// Generated by scripts/build-motion-lab-mcp-artifacts.mjs
// Source of truth:
// - lib/motion-lab-presets.js
// - data/motion-lab-preset-metadata.json

export const MOTION_LAB_HOSTED_VERSION = ${JSON.stringify(payload.version)};
export const MOTION_LAB_SUPPORTED_TRIGGERS = Object.freeze(${JSON.stringify(payload.supported_triggers, null, 2)});
export const MOTION_LAB_HOSTED_GROUPS = Object.freeze(${JSON.stringify(payload.groups, null, 2)});
export const MOTION_LAB_HOSTED_PRESET_IDS = Object.freeze(${JSON.stringify(payload.preset_ids, null, 2)});
export const MOTION_LAB_BASELINE_PRESETS = Object.freeze(${JSON.stringify(payload.baseline_presets, null, 2)});
export const MOTION_LAB_HOSTED_PRESET_METADATA = Object.freeze(${JSON.stringify(payload.preset_metadata_by_id, null, 2)});
export const MOTION_LAB_HOSTED_PRESETS = Object.freeze(${JSON.stringify(payload.presets_by_id, null, 2)});
`;
  writeFileSync(filePath, content, 'utf8');
}

mkdirSync(mcpGeneratedDir, { recursive: true });
mkdirSync(mcpPublicDir, { recursive: true });
mkdirSync(hostedSharedDir, { recursive: true });

writeJson(join(mcpGeneratedDir, 'motion-lab-baseline.json'), baselinePayload);
writeHostedTs(join(hostedSharedDir, 'generated.ts'), hostedPayload);
copyFileSync(join(repoRoot, 'material-export.js'), join(repoRoot, 'mcp', 'material-export.js'));
copyFileSync(join(repoRoot, 'public', 'icon-index.json'), join(mcpPublicDir, 'icon-index.json'));
copyFileSync(join(repoRoot, 'public', 'icon-index-solid.json'), join(mcpPublicDir, 'icon-index-solid.json'));
copyFileSync(join(repoRoot, 'public', 'synonyms.json'), join(mcpPublicDir, 'synonyms.json'));
copyFileSync(join(repoRoot, 'public', 'cjk-search-terms.json'), join(mcpPublicDir, 'cjk-search-terms.json'));
copyFileSync(join(repoRoot, 'public', 'multilingual-search-aliases.json'), join(mcpPublicDir, 'multilingual-search-aliases.json'));

console.log(`Motion Lab MCP artifacts built: ${baselinePresets.length} presets.`);
