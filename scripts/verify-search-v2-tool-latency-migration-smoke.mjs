import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const containerName = 'supericons_search_v2_tool_latency_smoke';
const postgresImage = 'public.ecr.aws/supabase/postgres:17.6.1.132';

function runDocker(args, { input = null, expectFailure = false } = {}) {
  const result = spawnSync('docker', args, { encoding: 'utf8', input });
  if (expectFailure) {
    assert.notEqual(result.status, 0, `Expected failure, received: ${result.stdout}`);
    return result;
  }
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result;
}

function removeContainer() {
  spawnSync('docker', ['rm', '-f', containerName], { encoding: 'utf8' });
}

function waitForDatabase() {
  for (let attempt = 0; attempt < 120; attempt += 1) {
    const result = spawnSync('docker', [
      'exec', containerName, 'pg_isready', '-U', 'postgres', '-d', 'postgres',
    ], { encoding: 'utf8' });
    if (result.status === 0) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Disposable PostgreSQL did not become ready.');
}

function waitForSupabaseBootstrap() {
  for (let attempt = 0; attempt < 120; attempt += 1) {
    const result = spawnSync('docker', [
      'exec', containerName, 'psql', '-U', 'postgres', '-d', 'postgres', '-tA', '-c',
      "select count(*) from pg_event_trigger where evtname = 'issue_graphql_placeholder'",
    ], { encoding: 'utf8' });
    if (result.status === 0 && result.stdout.trim() === '1') return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Supabase PostgreSQL bootstrap did not complete.');
}

function waitForStableDatabase() {
  let consecutiveReadyChecks = 0;
  for (let attempt = 0; attempt < 160; attempt += 1) {
    const result = spawnSync('docker', [
      'exec', containerName, 'pg_isready', '-U', 'supabase_admin', '-d', 'postgres',
    ], { encoding: 'utf8' });
    consecutiveReadyChecks = result.status === 0 ? consecutiveReadyChecks + 1 : 0;
    if (consecutiveReadyChecks >= 10) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 250);
  }
  throw new Error('Supabase PostgreSQL did not remain ready after bootstrap.');
}

function runSql(sql, { expectFailure = false } = {}) {
  const result = runDocker([
    'exec', '-i', containerName, 'psql', '-U', 'supabase_admin', '-d', 'postgres',
    '-v', 'ON_ERROR_STOP=1', '-tA',
  ], { input: sql, expectFailure });
  return expectFailure
    ? result.stderr
    : result.stdout.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
}

const prerequisiteSchema = `
alter event trigger issue_graphql_placeholder disable;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role; end if;
end $$;

create table public.search_request_audit (
  id bigserial primary key,
  query_norm text not null,
  source text not null,
  library_filter text,
  result_count integer not null default 0,
  status text not null default 'ok',
  latency_ms integer,
  session_hash text,
  ip_hash text,
  created_at timestamptz not null default timezone('utc', now())
);

create table public.mcp_usage_events (
  id bigint generated by default as identity primary key,
  event_id text not null default md5(random()::text || clock_timestamp()::text),
  request_id text,
  dedupe_key text,
  event_type text not null,
  channel text not null default 'unknown',
  environment text not null default 'production',
  client_family text not null default 'unknown',
  tool_name text,
  query_norm text,
  library_filter text,
  result_count integer,
  status text not null default 'ok',
  latency_ms integer,
  country_code text,
  geo_source text,
  locale text,
  anonymous_client_hash text,
  session_hash text,
  ip_hash text,
  user_agent_hash text,
  api_key_hash text,
  user_id uuid,
  is_registered boolean not null default false,
  is_pro boolean not null default false,
  account_plan text,
  subscription_status text,
  mcp_server_version text,
  search_request_audit_id bigint,
  created_at timestamptz not null default timezone('utc', now()),
  metadata jsonb not null default '{}'::jsonb
);
`;

removeContainer();
try {
  runDocker([
    'run', '--name', containerName,
    '-e', 'POSTGRES_PASSWORD=local-smoke-only',
    '-e', 'POSTGRES_DB=postgres',
    '-d', postgresImage,
  ]);
  waitForDatabase();
  waitForSupabaseBootstrap();
  waitForStableDatabase();
  runSql(prerequisiteSchema);

  runSql(readFileSync('supabase/migrations/20260712_search_v2_beta_measurement.sql', 'utf8'));
  const preflight = runSql(
    readFileSync('scripts/sql/search-v2-tool-latency-hosted-preflight.sql', 'utf8'),
  );
  assert.ok(preflight.includes('tool_latency_preflight_ok'));
  const migration = readFileSync(
    'supabase/migrations/20260714180000_search_v2_tool_latency_evidence.sql',
    'utf8',
  );
  runSql(migration);
  const postflight = runSql(
    readFileSync('scripts/sql/search-v2-tool-latency-hosted-postflight.sql', 'utf8'),
  );
  assert.ok(postflight.includes('tool_latency_postflight_ok'));
  runSql(migration);

  const schema = runSql(`
    select concat_ws('|',
      (select count(*) from information_schema.columns
        where table_schema = 'public' and table_name = 'search_request_audit'
          and column_name in ('worker_state', 'worker_request_ordinal', 'module_age_ms_at_handler_entry')),
      (select count(*) from pg_constraint
        where conname in (
          'search_request_audit_worker_state_valid',
          'search_request_audit_worker_ordinal_valid',
          'search_request_audit_module_age_valid'
        ) and convalidated = true),
      (select count(*) from pg_indexes
        where schemaname = 'public' and indexname in (
          'search_request_audit_beta_worker_created_at_idx',
          'mcp_usage_events_beta_tool_created_at_idx'
        )),
      (select count(*) from pg_proc
        where pronamespace = 'public'::regnamespace
          and proname = 'si_log_mcp_search_outcome_v2')
    );
  `);
  assert.ok(schema.includes('3|3|2|1'), `Unexpected schema result: ${schema.join(', ')}`);

  const valid = runSql(`
    begin;
    select public.si_log_mcp_search_outcome_v2(
      'tool-latency-valid', 3, 'all', 'strict', 'results', 'recommend_icons',
      repeat('a', 64), null, 'high', null, '0.4.18-beta.0', 1234
    );
    select concat_ws('|', tool_name, latency_ms, search_outcome, result_count)
    from public.mcp_usage_events
    where query_norm = 'tool-latency-valid'
    order by id desc limit 1;
    insert into public.search_request_audit (
      query_norm, source, result_count, worker_state, worker_request_ordinal,
      module_age_ms_at_handler_entry, beta_cohort
    ) values (
      'worker-valid', 'mcp_beta', 1, 'first_request', 1, 25, 'deterministic-v2-beta'
    );
    select concat_ws('|', worker_state, worker_request_ordinal, module_age_ms_at_handler_entry)
    from public.search_request_audit where query_norm = 'worker-valid';
    rollback;
  `);
  assert.ok(valid.includes('recommend_icons|1234|results|3'));
  assert.ok(valid.includes('first_request|1|25'));

  runSql(`
    select public.si_log_mcp_search_outcome_v2(
      'tool-latency-invalid', 0, 'all', 'strict', 'zero', 'search_icons',
      repeat('b', 64), null, 'low', null, '0.4.18-beta.0', -1
    );
  `, { expectFailure: true });
  runSql(`
    insert into public.search_request_audit (
      query_norm, source, result_count, worker_state, worker_request_ordinal,
      module_age_ms_at_handler_entry
    ) values ('worker-invalid', 'mcp_beta', 0, 'unknown', 0, -1);
  `, { expectFailure: true });

  console.log(JSON.stringify({
    status: 'ok',
    database: 'disposable_postgresql_17',
    migration: '20260714180000_search_v2_tool_latency_evidence.sql',
    idempotent_apply: true,
    worker_columns: 3,
    validated_constraints: 3,
    indexes: 2,
    latency_rpc: 'si_log_mcp_search_outcome_v2',
    valid_rows: 'inserted_and_rolled_back',
    invalid_latency_rejected: true,
    invalid_worker_context_rejected: true,
    hosted_preflight: 'passed',
    hosted_postflight: 'passed',
    hosted_systems_touched: false,
  }, null, 2));
} finally {
  removeContainer();
}
