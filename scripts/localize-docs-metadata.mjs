for (const locale of Object.keys(docsGroups)) {
  const file = path.join('data/i18n/messages', `${locale}.json`);
  const catalog = JSON.parse(fs.readFileSync(file, 'utf8'));
  catalog.docs.groups = { ...catalog.docs.groups, ...docsGroups[locale] };
  const pages = fillRemaining(locale, docsPages[locale] || translated[locale]);
  for (const [pageId, values] of Object.entries(pages)) {
    const [navLabel, kicker, pageTitle, summary] = values;
    const page = catalog.docs.pages[pageId] || {};
    page.navLabel = navLabel;
    page.kicker = kicker;
    page.pageTitle = pageTitle;
    if (summary === null) delete page.summary;
    else page.summary = summary;
    catalog.docs.pages[pageId] = page;
  }
  fs.writeFileSync(file, `${JSON.stringify(catalog, null, 2)}\n`);
}

