import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const containerName = 'supericons_admin_dashboard_phase_a_smoke';
const postgresImage = 'postgres:17-alpine';

function runDocker(args, { input = null, expectFailure = false } = {}) {
  const result = spawnSync('docker', args, { encoding: 'utf8', input });
  if (expectFailure) {
    assert.notEqual(result.status, 0, `Expected SQL failure, received: ${result.stdout}`);
    return result.stderr;
  }
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result.stdout;
}

function removeContainer() {
  spawnSync('docker', ['rm', '-f', containerName], { encoding: 'utf8' });
}

function waitForDatabase() {
  for (let attempt = 0; attempt < 90; attempt += 1) {
    const result = spawnSync('docker', [
      'exec', containerName, 'pg_isready', '-U', 'postgres', '-d', 'postgres',
    ], { encoding: 'utf8' });
    if (result.status === 0) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Disposable PostgreSQL did not become ready.');
}

function runSql(sql, options = {}) {
  return runDocker([
    'exec', '-i', containerName,
    'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-tA',
  ], { input: sql, ...options });
}

const prerequisiteSql = `
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role bypassrls; end if;
end $$;

create table public.search_request_audit (
  id bigserial primary key,
  query_norm text not null,
  source text not null,
  environment text,
  channel text,
  tool_name text,
  created_at timestamptz not null default timezone('utc', now())
);

create table public.mcp_usage_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  environment text not null default 'production',
  channel text not null default 'unknown',
  tool_name text,
  created_at timestamptz not null default timezone('utc', now())
);
`;

const migration = readFileSync(
  'supabase/migrations/20260716040000_admin_dashboard_phase_a.sql',
  'utf8',
);
const rollback = readFileSync(
  'supabase/rollbacks/20260716040000_admin_dashboard_phase_a.down.sql',
  'utf8',
);

removeContainer();
try {
  runDocker([
    'run', '--name', containerName,
    '-e', 'POSTGRES_PASSWORD=local-smoke-only',
    '-e', 'POSTGRES_DB=postgres',
    '-d', postgresImage,
  ]);
  waitForDatabase();
  runSql(prerequisiteSql);
  runSql('alter default privileges in schema public grant select on tables to anon, authenticated;');
  runSql(migration);
  runSql(migration);

  const schema = runSql(`
    select concat_ws('|',
      (select count(*) from information_schema.columns
        where table_schema = 'public' and table_name = 'mcp_usage_events'
          and column_name in ('query_origin', 'requested_limit', 'client_ip_public')),
      (select count(*) from pg_constraint
        where conname in ('mcp_usage_events_query_origin_valid', 'mcp_usage_events_requested_limit_valid')
          and convalidated = true),
      (select count(*) from information_schema.tables
        where table_schema = 'public'
          and table_name in ('admin_rollup_overview', 'admin_rollup_queries')),
      (select count(*) from pg_indexes
        where schemaname = 'public'
          and indexname in (
            'mcp_usage_events_admin_window_idx',
            'search_request_audit_admin_window_idx',
            'admin_rollup_overview_filters_idx',
            'admin_rollup_queries_filters_idx',
            'admin_rollup_queries_attention_idx'
          )),
      (select count(*) from pg_class
        where relnamespace = 'public'::regnamespace
          and relname in ('admin_rollup_overview', 'admin_rollup_queries')
          and relrowsecurity = true)
    );
  `).trim();
  assert.equal(schema, '3|2|2|5|2');

  runSql(`
    insert into public.mcp_usage_events (
      event_type, query_origin, requested_limit, client_ip_public
    ) values ('search_outcome', 'agent_query', 3, true);

    insert into public.admin_rollup_overview (
      day, channel, environment, query_origin, attempt_count, client_days
    ) values ('2026-07-15', 'hosted_mcp', 'production', 'agent_query', 10, 2);

    insert into public.admin_rollup_queries (
      day, query_norm, library_filter, query_origin, channel, environment, tool_name,
      attempt_count, first_seen, last_seen
    ) values (
      '2026-07-15', 'settings', 'all', 'agent_query', 'hosted_mcp', 'production',
      'search_icons', 10, '2026-07-15T01:00:00Z', '2026-07-15T02:00:00Z'
    );
  `);

  runSql("insert into public.mcp_usage_events (event_type, query_origin) values ('search_outcome', 'unknown');", { expectFailure: true });
  runSql("insert into public.mcp_usage_events (event_type, requested_limit) values ('search_outcome', 0);", { expectFailure: true });
  runSql(`
    insert into public.admin_rollup_queries (
      day, query_norm, library_filter, query_origin, channel, environment, tool_name,
      first_seen, last_seen
    ) values (
      '2026-07-15', 'bad order', 'all', 'agent_query', 'hosted_mcp', 'production',
      'search_icons', '2026-07-15T03:00:00Z', '2026-07-15T02:00:00Z'
    );
  `, { expectFailure: true });
  runSql('set role anon; select * from public.admin_rollup_overview;', { expectFailure: true });
  runSql('set role authenticated; select * from public.admin_rollup_queries;', { expectFailure: true });

  runSql(rollback);
  const rolledBack = runSql(`
    select concat_ws('|',
      to_regclass('public.admin_rollup_overview') is null,
      to_regclass('public.admin_rollup_queries') is null,
      (select count(*) from information_schema.columns
        where table_schema = 'public' and table_name = 'mcp_usage_events'
          and column_name in ('query_origin', 'requested_limit', 'client_ip_public'))
    );
  `).trim();
  assert.equal(rolledBack, 't|t|0');

  console.log(JSON.stringify({
    status: 'ok',
    database: 'disposable_postgresql_17',
    migration: '20260716040000_admin_dashboard_phase_a.sql',
    idempotent_apply: true,
    additive_columns: 3,
    validated_constraints: 2,
    private_rollup_tables: 2,
    supporting_indexes: 5,
    invalid_origin_rejected: true,
    invalid_limit_rejected: true,
    invalid_seen_order_rejected: true,
    public_role_reads_rejected: true,
    rollback_verified: true,
    hosted_systems_touched: false,
  }, null, 2));
} finally {
  removeContainer();
}
