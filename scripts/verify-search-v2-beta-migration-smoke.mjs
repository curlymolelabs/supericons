import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

import { aggregateLocaleAttemptCounts } from '../lib/search-beta-measurement.js';

const containerName = 'supericons_search_v2_beta_smoke';
const postgresImage = 'public.ecr.aws/supabase/postgres:17.6.1.132';
const localPassword = 'local-smoke-only';

function runDocker(args, { input = null, expectFailure = false } = {}) {
  const result = spawnSync('docker', args, {
    encoding: 'utf8',
    input,
  });
  if (expectFailure) {
    assert.notEqual(result.status, 0, `Expected failure, received: ${result.stdout}`);
    return result;
  }
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result;
}

function removeContainer() {
  spawnSync('docker', ['rm', '-f', containerName], { encoding: 'utf8' });
}

function waitForDatabase() {
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const result = spawnSync('docker', [
      'exec',
      containerName,
      'pg_isready',
      '-U',
      'postgres',
      '-d',
      'postgres',
    ], { encoding: 'utf8' });
    if (result.status === 0) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Disposable PostgreSQL did not become ready.');
}

function waitForSupabaseBootstrap() {
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const result = spawnSync('docker', [
      'exec',
      containerName,
      'psql',
      '-U',
      'postgres',
      '-d',
      'postgres',
      '-tA',
      '-c',
      "select count(*) from pg_event_trigger where evtname = 'issue_graphql_placeholder'",
    ], { encoding: 'utf8' });
    if (result.status === 0 && result.stdout.trim() === '1') return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Supabase PostgreSQL bootstrap did not complete.');
}

function waitForStableDatabase() {
  let consecutiveReadyChecks = 0;
  for (let attempt = 0; attempt < 120; attempt += 1) {
    const result = spawnSync('docker', [
      'exec',
      containerName,
      'pg_isready',
      '-U',
      'postgres',
      '-d',
      'postgres',
    ], { encoding: 'utf8' });
    consecutiveReadyChecks = result.status === 0 ? consecutiveReadyChecks + 1 : 0;
    if (consecutiveReadyChecks >= 10) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Disposable PostgreSQL did not remain stable after bootstrap.');
}

function queryDatabase(sql, { expectFailure = false, user = 'supabase_admin' } = {}) {
  const result = runDocker([
    'exec',
    '-i',
    containerName,
    'psql',
    '-U',
    user,
    '-d',
    'postgres',
    '-v',
    'ON_ERROR_STOP=1',
    '-tA',
    '-c',
    sql,
  ], { expectFailure });

  if (expectFailure) return result.stderr;
  return result.stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

const prerequisiteSchema = `
alter event trigger issue_graphql_placeholder disable;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role; end if;
end $$;

create table public.search_request_audit (
  id bigserial primary key,
  query_norm text not null,
  source text not null,
  library_filter text,
  result_count integer not null default 0,
  status text not null default 'ok',
  latency_ms integer,
  session_hash text,
  ip_hash text,
  created_at timestamptz not null default timezone('utc', now())
);

create table public.mcp_usage_events (
  id bigint generated by default as identity primary key,
  event_id text not null default md5(random()::text || clock_timestamp()::text),
  request_id text,
  dedupe_key text,
  event_type text not null,
  channel text not null default 'unknown',
  environment text not null default 'production',
  client_family text not null default 'unknown',
  tool_name text,
  query_norm text,
  library_filter text,
  result_count integer,
  status text not null default 'ok',
  locale text,
  session_hash text,
  mcp_server_version text,
  created_at timestamptz not null default timezone('utc', now())
);
`;

removeContainer();
try {
  runDocker([
    'run',
    '--name',
    containerName,
    '-e',
    `POSTGRES_PASSWORD=${localPassword}`,
    '-e',
    'POSTGRES_DB=postgres',
    '-d',
    postgresImage,
  ]);
  waitForDatabase();
  waitForSupabaseBootstrap();
  waitForStableDatabase();
  queryDatabase(prerequisiteSchema, { user: 'supabase_admin' });

  const hostedPreflight = readFileSync('scripts/sql/search-v2-beta-hosted-preflight.sql', 'utf8');
  const hostedPreflightResult = runDocker([
    'exec',
    '-i',
    containerName,
    'psql',
    '-U',
    'supabase_admin',
    '-d',
    'postgres',
    '-v',
    'ON_ERROR_STOP=1',
  ], { input: hostedPreflight });
  assert.match(hostedPreflightResult.stdout, /hosted_beta_preflight_ok/);

  const migration = readFileSync('supabase/migrations/20260712_search_v2_beta_measurement.sql', 'utf8');
  runDocker([
    'exec',
    '-i',
    containerName,
    'psql',
    '-U',
    'supabase_admin',
    '-d',
    'postgres',
    '-v',
    'ON_ERROR_STOP=1',
  ], { input: migration });

  const hostedPostflight = readFileSync('scripts/sql/search-v2-beta-hosted-postflight.sql', 'utf8');
  const hostedPostflightResult = runDocker([
    'exec',
    '-i',
    containerName,
    'psql',
    '-U',
    'supabase_admin',
    '-d',
    'postgres',
    '-v',
    'ON_ERROR_STOP=1',
  ], { input: hostedPostflight });
  assert.match(hostedPostflightResult.stdout, /hosted_beta_postflight_ok/);

  const schemaLines = queryDatabase(`
  select concat_ws('|',
    (
      select count(*) from information_schema.columns
      where table_schema = 'public'
        and table_name in ('search_request_audit', 'mcp_usage_events')
        and column_name in ('library_mode', 'search_outcome', 'confidence_label', 'beta_cohort')
    ),
    (
      select count(*) from pg_constraint
      where conname in (
        'search_request_audit_library_mode_valid',
        'search_request_audit_outcome_valid',
        'search_request_audit_confidence_label_valid',
        'mcp_usage_events_library_mode_valid',
        'mcp_usage_events_outcome_valid',
        'mcp_usage_events_confidence_label_valid'
      ) and convalidated = true
    ),
    (
      select count(*) from pg_indexes
      where schemaname = 'public'
        and indexname in (
          'search_request_audit_beta_cohort_created_at_idx',
          'mcp_usage_events_beta_cohort_created_at_idx'
        )
    ),
    (
      select count(*) from pg_proc
      where pronamespace = 'public'::regnamespace
        and proname = 'si_log_mcp_search_outcome'
    )
  );`);
  assert.ok(schemaLines.includes('8|6|2|1'), `Unexpected schema result: ${schemaLines.join(', ')}`);

  const validLines = queryDatabase(`
  begin;
  select public.si_log_mcp_search_outcome(
    'gate-a-valid-clarification', 0, 'all', 'all', 'clarification', 'recommend_icons',
    repeat('a', 64), 'en', 'low', 'deterministic-v2-beta', '0.4.18-beta.0'
  );
  select concat_ws('|', event_type, channel, environment, tool_name, library_mode, search_outcome, confidence_label, beta_cohort, locale, result_count)
  from public.mcp_usage_events
  where query_norm = 'gate-a-valid-clarification'
  order by id desc
  limit 1;
  rollback;`);
  assert.ok(
    validLines.includes('search_outcome|hosted_mcp|preview|recommend_icons|all|clarification|low|deterministic-v2-beta|en|0'),
    `Valid RPC row did not match: ${validLines.join(', ')}`,
  );

  const invalidCases = [
    ["'invalid'", "'zero'", "'low'", `repeat('b', 64)`],
    ["'strict'", "'invalid'", "'low'", `repeat('b', 64)`],
    ["'strict'", "'zero'", "'invalid'", `repeat('b', 64)`],
    ["'strict'", "'zero'", "'low'", "'not-a-sha256'"],
  ];
  for (const [libraryMode, searchOutcome, confidenceLabel, sessionHash] of invalidCases) {
    queryDatabase(`
      select public.si_log_mcp_search_outcome(
        'gate-a-invalid', 0, 'all', ${libraryMode}, ${searchOutcome}, 'search_icons',
        ${sessionHash}, 'en', ${confidenceLabel}, 'deterministic-v2-beta', '0.4.18-beta.0'
      );
    `, { expectFailure: true });
  }

  const denominatorLines = queryDatabase(`
  begin;
  select public.si_log_mcp_search_outcome(
    'gate-a-denominator-clarification', 0, 'all', 'all', 'clarification',
    'recommend_icons', repeat('c', 64), 'en', 'low', 'deterministic-v2-beta', '0.4.18-beta.0'
  );
  select public.si_log_mcp_search_outcome(
    'gate-a-denominator-zero', 0, 'all', 'all', 'zero',
    'search_icons', repeat('c', 64), 'en', 'low', 'deterministic-v2-beta', '0.4.18-beta.0'
  );
  select concat_ws('|',
    count(*),
    count(*) filter (where search_outcome = 'clarification'),
    count(*) filter (where search_outcome = 'zero')
  )
  from public.mcp_usage_events
  where query_norm in ('gate-a-denominator-clarification', 'gate-a-denominator-zero');
  rollback;`);
  assert.ok(denominatorLines.includes('2|1|1'), `Outcome separation failed: ${denominatorLines.join(', ')}`);

  const localeCounts = aggregateLocaleAttemptCounts([
    { locale_attempt_counts: { en: 3, ja: 2 } },
    { locale_attempt_counts: { en: 4, '(missing)': 1 } },
    { locale_attempt_counts: { th: 2, invalid: -1 } },
  ]);
  assert.deepEqual(localeCounts, {
    '(missing)': 1,
    en: 7,
    ja: 2,
    th: 2,
  });

  console.log(JSON.stringify({
    status: 'ok',
    database: 'disposable_postgresql_17',
    postgres_image: postgresImage,
    migration: '20260712_search_v2_beta_measurement.sql',
    columns_verified: 8,
    constraints_verified: 6,
    indexes_verified: 2,
    hosted_preflight: 'passed',
    hosted_postflight: 'passed_with_rows_rolled_back',
    rpc_success_path: 'passed_and_rolled_back',
    invalid_rpc_cases: invalidCases.length,
    clarification_zero_separation: 'passed_and_rolled_back',
    locale_count_export_helper: localeCounts,
    hosted_systems_touched: false,
  }, null, 2));
} finally {
  removeContainer();
}
