import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const containerName = 'supericons_material_asset_migration_smoke';
const postgresImage = 'postgres:17-alpine';

function runDocker(args, { input = null, expectFailure = false } = {}) {
  const result = spawnSync('docker', args, { encoding: 'utf8', input });
  if (expectFailure) {
    assert.notEqual(result.status, 0, `Expected SQL failure, received: ${result.stdout}`);
    return result.stderr;
  }
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result.stdout;
}

function removeContainer() {
  spawnSync('docker', ['rm', '-f', containerName], { encoding: 'utf8' });
}

function waitForDatabase() {
  for (let attempt = 0; attempt < 90; attempt += 1) {
    const result = spawnSync('docker', [
      'exec', containerName, 'pg_isready', '-U', 'postgres', '-d', 'postgres',
    ], { encoding: 'utf8' });
    if (result.status === 0) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 500);
  }
  throw new Error('Disposable PostgreSQL did not become ready.');
}

function runSql(sql, options = {}) {
  return runDocker([
    'exec', '-i', containerName,
    'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-tA',
  ], { input: sql, ...options });
}

const prerequisiteSql = `
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role bypassrls; end if;
end $$;

create table public.icon_catalog (
  icon_id text primary key,
  name text not null,
  source_library text not null,
  style text not null,
  icon_type text not null,
  search_text text not null
);

create table public.search_request_audit (
  id bigserial primary key,
  query_norm text not null,
  source text not null,
  result_count integer not null default 0,
  status text not null default 'ok',
  created_at timestamptz not null default timezone('utc', now())
);

create table public.mcp_usage_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  created_at timestamptz not null default timezone('utc', now())
);

insert into public.icon_catalog (icon_id, name, source_library, style, icon_type, search_text)
values ('material:settings', 'settings', 'material', 'outline', 'font', 'settings cog gear');
`;

const migration = readFileSync('supabase/migrations/20260714220000_material_icon_assets.sql', 'utf8');
const privateRolesMigration = readFileSync('supabase/migrations/20260714223000_material_icon_assets_private_roles.sql', 'utf8');
const hostedPreflight = readFileSync('scripts/sql/material-assets-hosted-preflight.sql', 'utf8');
const hostedPostflight = readFileSync('scripts/sql/material-assets-hosted-postflight.sql', 'utf8');
const recoveryPreflight = readFileSync('scripts/sql/material-assets-private-roles-recovery-preflight.sql', 'utf8');
const rollback = readFileSync('supabase/rollbacks/20260714220000_material_icon_assets.down.sql', 'utf8');
const privateRolesRollback = readFileSync('supabase/rollbacks/20260714223000_material_icon_assets_private_roles.down.sql', 'utf8');
const revision = 'a'.repeat(40);
const checksum = 'b'.repeat(64);

removeContainer();
try {
  runDocker([
    'run', '--name', containerName,
    '-e', 'POSTGRES_PASSWORD=local-smoke-only',
    '-e', 'POSTGRES_DB=postgres',
    '-d', postgresImage,
  ]);
  waitForDatabase();
  runSql(prerequisiteSql);
  runSql('alter default privileges in schema public grant select on tables to anon, authenticated;');
  runSql(hostedPreflight);
  runSql(migration);
  const productionPrivilegeFailure = runSql(hostedPostflight, { expectFailure: true });
  assert.match(productionPrivilegeFailure, /A public role can read material_icon_assets/);
  runSql(recoveryPreflight);
  runSql(privateRolesMigration);
  runSql(hostedPostflight);
  runSql(privateRolesMigration);
  runSql(migration);

  runSql(`
    set role service_role;
    insert into public.material_icon_assets (
      icon_id, variant, svg, axes, source_repo, source_revision, checksum
    ) values (
      'material:settings', 'outline', '<svg viewBox="0 0 24 24"></svg>',
      '{"fill":0,"wght":300,"grad":0,"opsz":24}',
      'google/material-design-icons', '${revision}', '${checksum}'
    );
    select icon_id from public.material_icon_assets;
    reset role;
  `);

  runSql("insert into public.material_icon_assets (icon_id, variant, svg, axes, source_repo, source_revision, checksum) values ('material:settings', 'solid', ' ', '{}', 'repo', repeat('a', 40), repeat('b', 64));", { expectFailure: true });
  runSql("insert into public.material_icon_assets (icon_id, variant, svg, axes, source_repo, source_revision, checksum) values ('material:settings', 'rounded', '<svg/>', '{}', 'repo', repeat('a', 40), repeat('b', 64));", { expectFailure: true });
  runSql("insert into public.search_request_audit (query_norm, source, error_code) values ('x', 'test', 'BAD-CODE');", { expectFailure: true });
  runSql('set role anon; select * from public.material_icon_assets;', { expectFailure: true });

  const schema = runSql(`
    select concat_ws('|',
      (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'material_icon_assets'),
      (select count(*) from information_schema.columns where table_schema = 'public' and table_name in ('search_request_audit', 'mcp_usage_events') and column_name = 'error_code'),
      (select count(*) from pg_constraint where conname in ('search_request_audit_error_code_valid', 'mcp_usage_events_error_code_valid') and convalidated = true),
      (select count(*) from pg_indexes where schemaname = 'public' and indexname in ('material_icon_assets_variant_revision_idx', 'search_request_audit_error_code_created_at_idx', 'mcp_usage_events_error_code_created_at_idx'))
    );
  `).trim();
  assert.equal(schema, '9|2|2|3');

  runSql(privateRolesRollback);
  runSql(rollback);
  const rolledBack = runSql(`
    select concat_ws('|',
      to_regclass('public.material_icon_assets') is null,
      (select count(*) from information_schema.columns where table_schema = 'public' and table_name in ('search_request_audit', 'mcp_usage_events') and column_name = 'error_code')
    );
  `).trim();
  assert.equal(rolledBack, 't|0');

  console.log(JSON.stringify({
    status: 'ok',
    migration_idempotent: true,
    hosted_preflight_verified: true,
    hosted_postflight_verified: true,
    production_default_privilege_mismatch_reproduced: true,
    private_role_recovery_verified: true,
    valid_service_role_write: true,
    invalid_svg_rejected: true,
    invalid_variant_rejected: true,
    invalid_error_code_rejected: true,
    anonymous_read_rejected: true,
    rollback_verified: true,
    hosted_systems_touched: false,
  }, null, 2));
} finally {
  removeContainer();
}
