import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

function normalizeText(value) {
  return String(value || '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[_:]+/g, ' ')
    .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
    .replace(/-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function uniqueStrings(values = []) {
  const seen = new Set();
  const output = [];

  for (const value of values) {
    const normalized = String(value || '').trim();
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    output.push(normalized);
  }

  return output;
}

function uniqueNormalized(values = []) {
  const seen = new Set();
  const output = [];

  for (const value of values) {
    const normalized = normalizeText(value);
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    output.push(normalized);
  }

  return output;
}

function normalizeIdentifier(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, '_')
    .replace(/[^a-z0-9_]/g, '')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '');
}

function uniqueIdentifiers(values = []) {
  const seen = new Set();
  const output = [];

  for (const value of values) {
    const normalized = normalizeIdentifier(value);
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    output.push(normalized);
  }

  return output;
}

function toArray(value) {
  return Array.isArray(value) ? value : [];
}

const sourcePath = resolve('data/search-intent-graph/intent-groups.json');
const coverageSourcePath = resolve('data/search-intent-graph/coverage-groups.json');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
const coverageSource = JSON.parse(readFileSync(coverageSourcePath, 'utf8'));

if (!Array.isArray(source.groups)) {
  throw new Error('intent-groups.json must contain a groups array');
}
if (!Array.isArray(coverageSource.groups)) {
  throw new Error('coverage-groups.json must contain a groups array');
}

const sourceGroups = [...source.groups, ...coverageSource.groups];

const groups = sourceGroups.map((group) => {
  const localizedPhrases =
    group.localized_phrases && typeof group.localized_phrases === 'object' ? group.localized_phrases : {};
  const localizedAliases = [];

  for (const [locale, phrases] of Object.entries(localizedPhrases)) {
    for (const phrase of toArray(phrases)) {
      const normalized = normalizeText(phrase);
      if (!normalized) continue;
      localizedAliases.push({
        locale,
        phrase: String(phrase).trim(),
        normalized,
      });
    }
  }

  const phraseAliases = toArray(group.phrases)
    .map((phrase) => ({
      locale: 'en',
      phrase: String(phrase).trim(),
      normalized: normalizeText(phrase),
    }))
    .filter((entry) => entry.phrase && entry.normalized);

  return {
    id: String(group.id || '').trim(),
    label: String(group.label || '').trim(),
    description: String(group.description || '').trim(),
    domains: uniqueNormalized(group.domains),
    facets: uniqueIdentifiers(group.facets),
    intentTypes: uniqueIdentifiers(group.intent_types),
    phrases: uniqueStrings(group.phrases),
    aliases: [...phraseAliases, ...localizedAliases],
    positiveConcepts: uniqueNormalized(group.positive_concepts),
    avoidConcepts: uniqueNormalized(group.avoid_concepts),
    fallbackTerms: uniqueNormalized(group.fallback_terms),
    resultFamilies: uniqueIdentifiers(group.result_families),
    suppressGroups: uniqueIdentifiers(group.suppress_groups),
    objects: uniqueNormalized(group.objects),
    actions: uniqueNormalized(group.actions),
    devices: uniqueNormalized(group.devices),
    gapStrategy: String(group.gap_strategy || '').trim(),
    confidenceFloor: String(group.confidence_floor || 'low').trim(),
  };
});

const phraseIndex = [];
for (const group of groups) {
  for (const alias of group.aliases) {
    phraseIndex.push({
      groupId: group.id,
      locale: alias.locale,
      phrase: alias.phrase,
      normalized: alias.normalized,
      tokenCount: alias.normalized.split(/\s+/).filter(Boolean).length,
      charLength: alias.normalized.length,
    });
  }
}

phraseIndex.sort(
  (left, right) =>
    right.charLength - left.charLength ||
    right.tokenCount - left.tokenCount ||
    left.groupId.localeCompare(right.groupId) ||
    left.normalized.localeCompare(right.normalized),
);

const output = `// Generated by scripts/build-search-intent-graph.mjs
// Do not edit by hand. Edit the source files in data/search-intent-graph instead.

export const GENERATED_INTENT_GRAPH_GROUPS = Object.freeze(${JSON.stringify(groups, null, 2)});

export const GENERATED_INTENT_GRAPH_PHRASES = Object.freeze(${JSON.stringify(phraseIndex, null, 2)});
`;

for (const target of [
  resolve('lib/generated-search-intent-graph.js'),
  resolve('mcp/runtime/generated-search-intent-graph.js'),
]) {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
}

console.log(`build-search-intent-graph: ok (${groups.length} groups, ${phraseIndex.length} phrases)`);
